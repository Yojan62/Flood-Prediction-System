# --- Pydantic Schemas ---

# Defines the shape of data expected when a request is sent to create a new location.
class LocationCreate(BaseModel):
    name: str
    latitude: float
    longitude: float

# Defines the shape of data expected for a subscription request.
class SubscriptionCreate(BaseModel):
    email: str
    location_id: int

# This schema defines the data to return when reading a location.
# It includes the location_id generated by the database.
class Location(BaseModel):
    location_id: int
    name: str
    latitude: float
    longitude: float

    # This Config tells Pydantic to read data from SQLAlchemy model objects.
    # 'from_attributes = True' is the modern replacement for 'orm_mode = True'.
    class Config:
        from_attributes = True


# --- FastAPI App Instance ---

# Creates the main app that will run the API.
app = FastAPI()

# --- Add CORS Middleware ---

# Defines the list of origins (websites) that are allowed to make requuests to my API.
origins = [
    "http://localhost:3000", # The address of the React frontend
]

# Adds the middleware to the FastAPI app.
app.add_middleware(
    CORSMiddleware,
    allow_origins=origins,            # Allows requests from the origins list.
    allow_credentials=True,           # Allows cookies to be included in requests.
    allow_methods=["*"],              # Allows all HTTP methods (GET, POST, OPTIONS, etc.)
    allow_headers=["*"],              # Allows all request headers.
)


# --- Database Dependency ---

# A reusable function that gets a database session for each API request.
# This ensures every connection to the database is properly closed.
def get_db():
    db = database.SessionLocal()
    try:
        yield db
    finally:
        db.close()


# --- API Endpoints ---

