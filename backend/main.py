@app.get("/api/test-db")
async def test_database_connection(db: Session = Depends(get_db)):
    # An endpoint to test if the backend can successfully connect to the database.
    try:
        # Wraps the raw SQL 'SELECT 1' query in the text() function for safety.
        db.execute(text('SELECT 1'))
        return {"status": "success", "message": "Database connection is working!"}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Database connection failed: {str(e)}")


@app.post("/api/test-email")
async def send_test_email(to_email: str):
    # An endpoint to send a test email using SendGrid to verify it works.

    # Loads the SendGrid API key securely from the .env file.
    sendgrid_api_key = os.getenv("SENDGRID_API_KEY")
    # Loads the verified sender email address securely from the .env file.
    from_email_address = os.getenv("SENDGRID_FROM_EMAIL")

    # Checks if the API key and sender email are configured.
    if not sendgrid_api_key:
        raise HTTPException(status_code=500, detail="SendGrid API key not configured in .env file")
    if not from_email_address:
         raise HTTPException(status_code=500, detail="SENDGRID_FROM_EMAIL not configured in .env file.")

    # Creates the email message object with a subject and content.
    message = Mail(
        from_email=from_email_address,
        to_emails=to_email,
        subject='Test Email from Flood Prediction System',
        html_content='<strong>This is a test email to confirm SendGrid is working!</strong>'
    )
    try:
        # Creates the SendGrid client and attempts to send the email.
        sg = SendGridAPIClient(sendgrid_api_key)
        response = sg.send(message)
        # Returns the status code from SendGrid if successful.
        return {"status": "success", "sendgrid_status_code": response.status_code}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to send email: {str(e)}")

@app.get("/api/locations", response_model=list[Location])
async def get_locations(db: Session = Depends(get_db)):
    # This queries the database for all records in the 'locations' table.
    locations = db.query(models.Location).all()
    # It returns the list, which FastAPI will automatically
    # convert to JSON using the 'Location' Pydantic schema.
    return locations

@app.post("/api/locations")
async def create_location(location: LocationCreate, db: Session = Depends(get_db)):
    # An endpoint to add a new location to the 'locations' table.

    # Creates an instance of the SQLAlchemy Location model from the request data.
    db_location = models.Location(
        name=location.name,
        latitude=location.latitude,
        longitude=location.longitude
    )

    # Adds the new location object to the database session.
    db.add(db_location)

    # Commits the session to permanently save the new record in the database.
    db.commit()

    # Refreshes the object to get the new 'location_id' generated by the database.
    db.refresh(db_location)

    # Returns the complete data for the newly created location.
    return db_location

@app.post("/api/subscribe")
async def subscribe_user(subscription: SubscriptionCreate, db: Session = Depends(get_db)):
    """
    Handles user subscription requests.
    Validates the location ID, checks for duplicates, and saves the new user to the database.
    """
    # --- 1. Validate Location ---
    # Finds the location the user wants to subscribe to.
    location = db.query(models.Location).filter(models.Location.location_id == subscription.location_id).first()
    
    # If the location doesn't exist, return a 404 error.
    if not location:
        raise HTTPException(status_code=404, detail=f"Location with id {subscription.location_id} not found.")

    # --- 2. Check for Duplicates ---
    # Checks if this email is already subscribed to this specific location.
    existing_user = db.query(models.User).filter(
        models.User.email == subscription.email, # Use the correct 'email' field
        models.User.subscribed_location_id == subscription.location_id
    ).first()

    # --- 3. Use the variable (This is where your error happened) ---
    if existing_user:
        # If they are already subscribed, just return a success message.
        return {"status": "success", "message": f"{subscription.email} is already subscribed to {location.name}."}

    # --- 4. Create New User ---
    # Creates the new user object using the SQLAlchemy model.
    db_user = models.User(
        email=subscription.email,
        subscribed_location_id=subscription.location_id
    )

    try:
        # --- 5. Save to Database ---
        # Adds the new user to the session and commits the change.
        db.add(db_user)
        db.commit()
        # Refreshes the object to get the new user_id from the database.
        db.refresh(db_user)
        
        # --- 6. Return Confirmation ---
        return {"status": "success", "message": f"User subscribed to {location.name} successfully.", "user_id": db_user.user_id}
    except Exception as e:
        # If anything goes wrong, rolls back the change and returns an error.
        db.rollback()
        print(f"Database error during subscription: {e}") # Logs the error for debugging.
        raise HTTPException(status_code=500, detail="Could not save subscription due to a database error.")